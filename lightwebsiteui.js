  /* ---------- 10. Counters, countdown, gallery, reveal ---------- */
  function animateCount(node) {
    const target = parseFloat(node.dataset.count);
    const suffix = node.dataset.suffix || '';
    const start = performance.now();
    function tick(now) {
      const t = Math.min(1, (now - start) / 1500);
      const v = target * (1 - Math.pow(1 - t, 3));
      node.textContent = (Number.isInteger(target) ? Math.round(v) : v.toFixed(1)).toLocaleString('ru-RU') + suffix;
      if (t < 1) requestAnimationFrame(tick);
    }
    requestAnimationFrame(tick);
  }

  function setupTimers() {
    fresh($$('[data-timer]'), 'timer').forEach(node => {
      const end = new Date(node.dataset.timer).getTime();
      node.classList.add('bui-timer');
      function render() {
        let left = Math.max(0, Math.floor((end - Date.now()) / 1000));
        if (!left) { node.textContent = node.dataset.done || tx.timerDone; return false; }
        const parts = [[Math.floor(left / 86400), tx.days], [Math.floor(left / 3600) % 24, tx.hours], [Math.floor(left / 60) % 60, tx.minutes], [left % 60, tx.seconds]];
        node.innerHTML = parts.map(([v, l]) => '<span>' + String(v).padStart(2, '0') + '<small>' + l + '</small></span>').join('');
        return true;
      }
      if (render()) {
        // The timer stops itself when its node leaves the page (single-page apps)
        const id = setInterval(() => { if (!node.isConnected || !render()) clearInterval(id); }, 1000);
        intervals.push(id);
      }
    });
  }

