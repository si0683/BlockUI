  function isLight(hex) {
    const rgb = hex.replace('#', '').match(/\w\w/g);
    if (!rgb) return true;
    const [r, g, b] = rgb.map(h => parseInt(h, 16));
    return (r * 299 + g * 587 + b * 114) / 1000 > 150;
  }

